# Creates lab copies of the game for local multi-instance testing: private\lab-host, private\lab-client.
# Exe and DLLs are hardlinked and DaveTheDiver_Data/DLC/D3D12 are junctioned, so never edit game bytes through a
# lab copy. BepInEx is unpacked into each copy (never into the real install); the first copy generates the interop
# assemblies and the others reuse them. steam_appid.txt keeps a direct launch from being relaunched by Steam.
param([string[]]$Names = @('host', 'client'), [string]$BepInExZip = '')
$ErrorActionPreference = 'Stop'
$mod = Split-Path -Parent $PSScriptRoot
. (Join-Path $PSScriptRoot 'game-dir.ps1'); $game = Get-DaveDir
if (-not $BepInExZip) { $BepInExZip = Join-Path $mod 'private\BepInEx-Unity.IL2CPP-win-x64-6.0.0-be.790.zip' }
if (-not (Test-Path $BepInExZip)) { throw "BepInEx zip missing: $BepInExZip (gh release download bepinex-6.0.0-be.790 -R multiplayereverything/Dave-The-Divers-Coop -D private)" }
foreach ($name in $Names) {
    $lab = Join-Path $mod "private\lab-$name"
    New-Item -ItemType Directory -Force $lab | Out-Null
    foreach ($file in 'DaveTheDiver.exe', 'GameAssembly.dll', 'UnityPlayer.dll', 'baselib.dll', 'UnityCrashHandler64.exe') {
        $dst = Join-Path $lab $file
        if (-not (Test-Path $dst)) { New-Item -ItemType HardLink -Path $dst -Target (Join-Path $game $file) | Out-Null }
    }
    foreach ($dir in 'DaveTheDiver_Data', 'DLC', 'D3D12') {
        $dst = Join-Path $lab $dir
        if (-not (Test-Path $dst)) { New-Item -ItemType Junction -Path $dst -Target (Join-Path $game $dir) | Out-Null }
    }
    if (-not (Test-Path (Join-Path $lab 'BepInEx\core'))) { Expand-Archive -Path $BepInExZip -DestinationPath $lab -Force }
    # Reuse interop generated by an earlier copy (same game build) instead of regenerating it per copy.
    $first = Join-Path $mod 'private\lab-host\BepInEx'
    if ($name -ne 'host' -and (Test-Path "$first\interop") -and -not (Test-Path "$lab\BepInEx\interop")) {
        foreach ($dir in 'interop', 'unity-libs', 'cache') { Copy-Item "$first\$dir" "$lab\BepInEx\$dir" -Recurse -Force -ErrorAction SilentlyContinue }
    }
    New-Item -ItemType Directory -Force "$lab\BepInEx\plugins\DaveTheDiverMP", "$lab\BepInEx\config" | Out-Null
    Set-Content -Path (Join-Path $lab 'steam_appid.txt') -Value '1868140' -NoNewline
    Write-Host "Lab copy ready: $lab"
}
